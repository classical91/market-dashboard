"use strict";

const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const { withExclusiveLock, writeJsonAtomic, readJsonStore } = require("./json-file-lock");
const { formatLabel, extractTags } = require("../../public/assets/js/ticker-label");

/**
 * Potential Buys — a holding area for screenshots of stocks and crypto tokens
 * worth a closer look. Nothing is analysed or traded on arrival: a screenshot
 * stays until it is deleted from the page.
 *
 * Images live as files in `<DATA_DIR>/potential-buys/`, and their metadata
 * (label, size, when it arrived) in `<DATA_DIR>/potential-buys.json`, so both
 * survive restarts on the Railway volume.
 */

const MAX_BYTES = 15 * 1024 * 1024;
const MAX_LABEL_CHARS = 140;
const MAX_ITEMS = 1000;

const EXTENSIONS = {
  "image/jpeg": "jpg",
  "image/png": "png",
  "image/webp": "webp",
  "image/gif": "gif",
};

/**
 * Ids are generated by the server (`<ms>-<hex>`). Only that exact shape is
 * accepted back from a client, so a delete can never reach outside the
 * screenshot folder.
 */
const ID_RE = /^\d{10,16}-[a-f0-9]{8}$/;

function isPotentialBuyId(value) {
  return typeof value === "string" && ID_RE.test(value);
}

/**
 * Screenshots dropped together share a batch id chosen by the page, so they
 * read as one entry (several images side by side). Only this shape is kept;
 * anything else is dropped rather than refused, so a bad id never loses a
 * screenshot.
 */
const BATCH_RE = /^[a-z0-9][a-z0-9-]{5,39}$/;

function normalizeBatch(value) {
  return typeof value === "string" && BATCH_RE.test(value) ? value : "";
}

function httpError(message, statusCode) {
  const err = new Error(message);
  err.statusCode = statusCode;
  err.expose = true;
  return err;
}

/**
 * What the bytes actually are, from their leading "magic" bytes. The declared
 * Content-Type is only a hint, so the stored file and its extension always
 * agree with what a browser will be asked to render.
 */
function sniffImage(bytes) {
  const starts = (sig, at = 0) => sig.every((b, i) => bytes[at + i] === b);
  const ascii = (at, len) => bytes.subarray(at, at + len).toString("latin1");
  if (bytes.length >= 3 && starts([0xff, 0xd8, 0xff])) return { kind: "image", mimeType: "image/jpeg" };
  if (bytes.length >= 8 && starts([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])) {
    return { kind: "image", mimeType: "image/png" };
  }
  if (bytes.length >= 6 && (ascii(0, 6) === "GIF87a" || ascii(0, 6) === "GIF89a")) {
    return { kind: "image", mimeType: "image/gif" };
  }
  if (bytes.length >= 12 && ascii(0, 4) === "RIFF" && ascii(8, 4) === "WEBP") {
    return { kind: "image", mimeType: "image/webp" };
  }
  if (bytes.length >= 12 && ascii(4, 4) === "ftyp" && /^(heic|heix|hevc|hevx|heim|heis|mif1|msf1)$/.test(ascii(8, 4))) {
    return { kind: "heic" };
  }
  return { kind: "unknown" };
}

/**
 * A label's folders are its tickers: "$BTC breakout #crypto" files the
 * screenshot under BTC and CRYPTO, and a label that is one ticker-shaped word
 * ("btc", "Total3") is saved as "$BTC" / "$TOTAL3". Shared with the page —
 * see public/assets/js/ticker-label.js.
 *
 * One folder per ticker: how many screenshots carry it and when the newest
 * of them was added, relabelled or cropped. Sorted most recently updated
 * first. Screenshots without a tag are counted as `untagged`.
 */
function buildFolders(items) {
  const byTag = new Map();
  let untagged = 0;
  for (const item of items) {
    const tags = item.tags || extractTags(item.label);
    if (!tags.length) untagged += 1;
    const touched = item.updatedAt || item.createdAt || 0;
    for (const tag of tags) {
      const folder = byTag.get(tag) || { tag, count: 0, updatedAt: 0 };
      folder.count += 1;
      folder.updatedAt = Math.max(folder.updatedAt, touched);
      byTag.set(tag, folder);
    }
  }
  const folders = [...byTag.values()].sort((a, b) => b.updatedAt - a.updatedAt || a.tag.localeCompare(b.tag));
  return { folders, untagged };
}

const DAY_MS = 24 * 60 * 60 * 1000;
// The page marks a screenshot red once it is older than this; see STALE_MS in
// public/assets/js/potential-buys.js.
const STALE_MS = 3 * DAY_MS;

/**
 * Counts only, for Main Hub's System Logs card: never an id, label, file name
 * or image URL. `tickers` is how many distinct $tickers/#tags are in use; `newestAt`
 * and `oldestAt` are when the newest and oldest screenshot were added.
 * `olderThan3d` / `olderThan3dTickers` match the page's "Older than 3 days"
 * card: screenshots past the red line, and how many tickers they cover.
 */
function summarize(items, now = Date.now()) {
  const { folders, untagged } = buildFolders(items);
  let addedLast24h = 0;
  let addedLast7d = 0;
  let newestAt = null;
  let oldestAt = null;
  let olderThan3d = 0;
  const staleTickers = new Set();
  for (const item of items) {
    const created = Number(item.createdAt) || 0;
    if (!created) continue;
    if (created >= now - DAY_MS) addedLast24h += 1;
    if (created >= now - 7 * DAY_MS) addedLast7d += 1;
    if (now - created > STALE_MS) {
      olderThan3d += 1;
      for (const tag of item.tags || extractTags(item.label)) staleTickers.add(tag);
    }
    if (newestAt === null || created > newestAt) newestAt = created;
    if (oldestAt === null || created < oldestAt) oldestAt = created;
  }
  return {
    total: items.length,
    tickers: folders.length,
    untagged,
    addedLast24h,
    addedLast7d,
    olderThan3d,
    olderThan3dTickers: staleTickers.size,
    newestAt,
    oldestAt,
    generatedAt: now,
  };
}

function normalizeLabel(value, maxChars = MAX_LABEL_CHARS) {
  if (value === undefined || value === null) return "";
  if (typeof value !== "string") throw httpError("label must be text", 400);
  return formatLabel(value).slice(0, maxChars).trim();
}

class PotentialBuysStore {
  /**
   * `name` picks the folder and JSON file under DATA_DIR and `title` the
   * name used in error messages, so another page (Active Trades' screenshot
   * notes) can keep its own separate collection with the same rules.
   * `maxLabelChars` lets that collection take longer notes.
   */
  constructor({
    dataDir,
    name = "potential-buys",
    title = "Potential Buys",
    urlPrefix = "/potential-buys-images",
    maxLabelChars = MAX_LABEL_CHARS,
    now = () => Date.now(),
    logger = console,
  }) {
    this.dir = path.join(dataDir, name);
    this.file = path.join(dataDir, `${name}.json`);
    this.title = title;
    this.urlPrefix = urlPrefix;
    this.maxLabelChars = maxLabelChars;
    this.now = now;
    this.logger = logger;
    this._lock = { depth: 0 };
  }

  _read() {
    const parsed = readJsonStore(this.file, this.logger, "[PotentialBuys]");
    return parsed && Array.isArray(parsed.items) ? parsed.items : [];
  }

  _write(items) {
    if (!writeJsonAtomic(this.file, { version: 1, items }, this.logger, "[PotentialBuys]")) {
      throw httpError(`Couldn't save the ${this.title} list; try again.`, 500);
    }
  }

  _withLock(operation) {
    return withExclusiveLock(this.file, this._lock, operation, {
      busyMessage: `${this.title} is busy; retry in a moment.`,
    });
  }

  _present(item) {
    return {
      ...item,
      // Older labels ("Btc") read as tickers ("$BTC") without a rewrite.
      label: formatLabel(item.label),
      updatedAt: item.updatedAt || item.createdAt,
      tags: extractTags(item.label),
      url: `${this.urlPrefix}/${item.file}`,
    };
  }

  /** Every stored screenshot, newest first. */
  list() {
    return this._read()
      .slice()
      .sort((a, b) => b.createdAt - a.createdAt)
      .map((item) => this._present(item));
  }

  /** Hashtag folders with their counts and last-updated time. */
  folders(items = this.list()) {
    return buildFolders(items);
  }

  /** Counts only — see summarize(). */
  summary() {
    return summarize(this.list(), this.now());
  }

  /** Store one screenshot from its raw bytes. */
  add(bytes, { label, batch } = {}) {
    const sniffed = this._checkImage(bytes);
    const cleanLabel = normalizeLabel(label, this.maxLabelChars);
    const cleanBatch = normalizeBatch(batch);
    return this._withLock(() => {
      const items = this._read();
      if (items.length >= MAX_ITEMS) {
        throw httpError(`${this.title} holds at most ${MAX_ITEMS} screenshots; delete some first.`, 409);
      }
      const createdAt = this.now();
      const id = `${createdAt}-${crypto.randomBytes(4).toString("hex")}`;
      const file = `${id}.${EXTENSIONS[sniffed.mimeType]}`;
      fs.mkdirSync(this.dir, { recursive: true });
      fs.writeFileSync(path.join(this.dir, file), bytes, { flag: "wx" });
      const item = {
        id, file, label: cleanLabel, mimeType: sniffed.mimeType, size: bytes.length, createdAt, updatedAt: createdAt,
      };
      if (cleanBatch) item.batch = cleanBatch;
      try {
        this._write([item, ...items]);
      } catch (err) {
        try { fs.unlinkSync(path.join(this.dir, file)); } catch {}
        throw err;
      }
      return this._present(item);
    });
  }

  /**
   * Swap a screenshot's picture for a cropped version of it. The crop is
   * saved under a new file name (images are served as immutable), and the
   * old file is removed once the list points at the new one.
   */
  replaceImage(id, bytes) {
    if (!isPotentialBuyId(id)) throw httpError("Unknown screenshot id.", 400);
    const sniffed = this._checkImage(bytes);
    return this._withLock(() => {
      const items = this._read();
      const item = items.find((entry) => entry.id === id);
      if (!item) throw httpError(`That screenshot is no longer in ${this.title}.`, 404);
      const updatedAt = Math.max(this.now(), (item.updatedAt || item.createdAt || 0) + 1);
      const file = `${id}-c${updatedAt}-${crypto.randomBytes(2).toString("hex")}.${EXTENSIONS[sniffed.mimeType]}`;
      fs.mkdirSync(this.dir, { recursive: true });
      fs.writeFileSync(path.join(this.dir, file), bytes, { flag: "wx" });
      const previousFile = item.file;
      Object.assign(item, { file, mimeType: sniffed.mimeType, size: bytes.length, updatedAt, croppedAt: updatedAt });
      try {
        this._write(items);
      } catch (err) {
        try { fs.unlinkSync(path.join(this.dir, file)); } catch {}
        throw err;
      }
      this._unlink(previousFile);
      return this._present(item);
    });
  }

  _unlink(file) {
    try {
      fs.unlinkSync(path.join(this.dir, file));
    } catch (err) {
      if (err.code !== "ENOENT") this.logger.error?.(`[PotentialBuys] Could not delete ${file}:`, err.message);
    }
  }

  _checkImage(bytes) {
    if (!Buffer.isBuffer(bytes) || bytes.length === 0) {
      throw httpError("Send the screenshot's bytes as the request body (an image Content-Type).", 400);
    }
    if (bytes.length > MAX_BYTES) throw httpError("Screenshot is larger than 15 MB.", 413);
    const sniffed = sniffImage(bytes);
    if (sniffed.kind === "heic") {
      throw httpError(
        "That photo is HEIC, which browsers can't show. In the Shortcut, add a \"Convert Image\" to JPEG step " +
          "before Get Contents of URL, or send a PNG/JPEG screenshot.",
        415,
      );
    }
    if (sniffed.kind !== "image") {
      throw httpError(
        `That isn't a PNG, JPEG, WebP or GIF image (got ${bytes.length} bytes of something else). ` +
          "In the Shortcut, set Request Body to File and pick the image (Shortcut Input), not text.",
        415,
      );
    }

    return sniffed;
  }

  /** Change a screenshot's label (ticker, note). */
  update(id, { label }) {
    if (!isPotentialBuyId(id)) throw httpError("Unknown screenshot id.", 400);
    const cleanLabel = normalizeLabel(label, this.maxLabelChars);
    return this._withLock(() => {
      const items = this._read();
      const item = items.find((entry) => entry.id === id);
      if (!item) throw httpError(`That screenshot is no longer in ${this.title}.`, 404);
      if (item.label !== cleanLabel) {
        item.label = cleanLabel;
        item.updatedAt = Math.max(this.now(), (item.updatedAt || item.createdAt || 0) + 1);
        this._write(items);
      }
      return this._present(item);
    });
  }

  /** Delete a screenshot and its image file. */
  remove(id) {
    if (!isPotentialBuyId(id)) throw httpError("Unknown screenshot id.", 400);
    return this._withLock(() => {
      const items = this._read();
      const item = items.find((entry) => entry.id === id);
      if (!item) throw httpError(`That screenshot is no longer in ${this.title}.`, 404);
      this._write(items.filter((entry) => entry.id !== id));
      // The list is the source of truth: once the entry is gone the page no
      // longer shows it, so a leftover file is only wasted space, not a ghost.
      this._unlink(item.file);
      return { id };
    });
  }
}

module.exports = {
  PotentialBuysStore,
  isPotentialBuyId,
  sniffImage,
  extractTags,
  buildFolders,
  summarize,
  MAX_BYTES,
  MAX_LABEL_CHARS,
};
