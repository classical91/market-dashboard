"use strict";

const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const { withExclusiveLock, writeJsonAtomic, readJsonStore } = require("./json-file-lock");

/**
 * Potential Buys — a holding area for screenshots of stocks and crypto tokens
 * worth a closer look. Nothing is analysed or traded on arrival: a screenshot
 * stays until it is deleted from the page.
 *
 * Images live as files in `<DATA_DIR>/potential-buys/`, and their metadata
 * (label, size, when it arrived) in `<DATA_DIR>/potential-buys.json`, so both
 * survive restarts on the Railway volume.
 */

const MAX_BYTES = 15 * 1024 * 1024;
const MAX_LABEL_CHARS = 140;
const MAX_ITEMS = 1000;

const EXTENSIONS = {
  "image/jpeg": "jpg",
  "image/png": "png",
  "image/webp": "webp",
  "image/gif": "gif",
};

/**
 * Ids are generated by the server (`<ms>-<hex>`). Only that exact shape is
 * accepted back from a client, so a delete can never reach outside the
 * screenshot folder.
 */
const ID_RE = /^\d{10,16}-[a-f0-9]{8}$/;

function isPotentialBuyId(value) {
  return typeof value === "string" && ID_RE.test(value);
}

function httpError(message, statusCode) {
  const err = new Error(message);
  err.statusCode = statusCode;
  err.expose = true;
  return err;
}

/**
 * What the bytes actually are, from their leading "magic" bytes. The declared
 * Content-Type is only a hint, so the stored file and its extension always
 * agree with what a browser will be asked to render.
 */
function sniffImage(bytes) {
  const starts = (sig, at = 0) => sig.every((b, i) => bytes[at + i] === b);
  const ascii = (at, len) => bytes.subarray(at, at + len).toString("latin1");
  if (bytes.length >= 3 && starts([0xff, 0xd8, 0xff])) return { kind: "image", mimeType: "image/jpeg" };
  if (bytes.length >= 8 && starts([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])) {
    return { kind: "image", mimeType: "image/png" };
  }
  if (bytes.length >= 6 && (ascii(0, 6) === "GIF87a" || ascii(0, 6) === "GIF89a")) {
    return { kind: "image", mimeType: "image/gif" };
  }
  if (bytes.length >= 12 && ascii(0, 4) === "RIFF" && ascii(8, 4) === "WEBP") {
    return { kind: "image", mimeType: "image/webp" };
  }
  if (bytes.length >= 12 && ascii(4, 4) === "ftyp" && /^(heic|heix|hevc|hevx|heim|heis|mif1|msf1)$/.test(ascii(8, 4))) {
    return { kind: "heic" };
  }
  return { kind: "unknown" };
}

function normalizeLabel(value) {
  if (value === undefined || value === null) return "";
  if (typeof value !== "string") throw httpError("label must be text", 400);
  return value.replace(/\s+/g, " ").trim().slice(0, MAX_LABEL_CHARS);
}

class PotentialBuysStore {
  constructor({ dataDir, urlPrefix = "/potential-buys-images", now = () => Date.now(), logger = console }) {
    this.dir = path.join(dataDir, "potential-buys");
    this.file = path.join(dataDir, "potential-buys.json");
    this.urlPrefix = urlPrefix;
    this.now = now;
    this.logger = logger;
    this._lock = { depth: 0 };
  }

  _read() {
    const parsed = readJsonStore(this.file, this.logger, "[PotentialBuys]");
    return parsed && Array.isArray(parsed.items) ? parsed.items : [];
  }

  _write(items) {
    if (!writeJsonAtomic(this.file, { version: 1, items }, this.logger, "[PotentialBuys]")) {
      throw httpError("Couldn't save the Potential Buys list; try again.", 500);
    }
  }

  _withLock(operation) {
    return withExclusiveLock(this.file, this._lock, operation, {
      busyMessage: "Potential Buys is busy; retry in a moment.",
    });
  }

  _present(item) {
    return { ...item, url: `${this.urlPrefix}/${item.file}` };
  }

  /** Every stored screenshot, newest first. */
  list() {
    return this._read()
      .slice()
      .sort((a, b) => b.createdAt - a.createdAt)
      .map((item) => this._present(item));
  }

  /** Store one screenshot from its raw bytes. */
  add(bytes, { label } = {}) {
    if (!Buffer.isBuffer(bytes) || bytes.length === 0) {
      throw httpError("Send the screenshot's bytes as the request body (an image Content-Type).", 400);
    }
    if (bytes.length > MAX_BYTES) throw httpError("Screenshot is larger than 15 MB.", 413);
    const sniffed = sniffImage(bytes);
    if (sniffed.kind === "heic") {
      throw httpError(
        "That photo is HEIC, which browsers can't show. In the Shortcut, add a \"Convert Image\" to JPEG step " +
          "before Get Contents of URL, or send a PNG/JPEG screenshot.",
        415,
      );
    }
    if (sniffed.kind !== "image") {
      throw httpError(
        `That isn't a PNG, JPEG, WebP or GIF image (got ${bytes.length} bytes of something else). ` +
          "In the Shortcut, set Request Body to File and pick the image (Shortcut Input), not text.",
        415,
      );
    }

    const cleanLabel = normalizeLabel(label);
    return this._withLock(() => {
      const items = this._read();
      if (items.length >= MAX_ITEMS) {
        throw httpError(`Potential Buys holds at most ${MAX_ITEMS} screenshots; delete some first.`, 409);
      }
      const createdAt = this.now();
      const id = `${createdAt}-${crypto.randomBytes(4).toString("hex")}`;
      const file = `${id}.${EXTENSIONS[sniffed.mimeType]}`;
      fs.mkdirSync(this.dir, { recursive: true });
      fs.writeFileSync(path.join(this.dir, file), bytes, { flag: "wx" });
      const item = { id, file, label: cleanLabel, mimeType: sniffed.mimeType, size: bytes.length, createdAt };
      try {
        this._write([item, ...items]);
      } catch (err) {
        try { fs.unlinkSync(path.join(this.dir, file)); } catch {}
        throw err;
      }
      return this._present(item);
    });
  }

  /** Change a screenshot's label (ticker, note). */
  update(id, { label }) {
    if (!isPotentialBuyId(id)) throw httpError("Unknown screenshot id.", 400);
    const cleanLabel = normalizeLabel(label);
    return this._withLock(() => {
      const items = this._read();
      const item = items.find((entry) => entry.id === id);
      if (!item) throw httpError("That screenshot is no longer in Potential Buys.", 404);
      item.label = cleanLabel;
      this._write(items);
      return this._present(item);
    });
  }

  /** Delete a screenshot and its image file. */
  remove(id) {
    if (!isPotentialBuyId(id)) throw httpError("Unknown screenshot id.", 400);
    return this._withLock(() => {
      const items = this._read();
      const item = items.find((entry) => entry.id === id);
      if (!item) throw httpError("That screenshot is no longer in Potential Buys.", 404);
      this._write(items.filter((entry) => entry.id !== id));
      // The list is the source of truth: once the entry is gone the page no
      // longer shows it, so a leftover file is only wasted space, not a ghost.
      try {
        fs.unlinkSync(path.join(this.dir, item.file));
      } catch (err) {
        if (err.code !== "ENOENT") this.logger.error?.(`[PotentialBuys] Could not delete ${item.file}:`, err.message);
      }
      return { id };
    });
  }
}

module.exports = {
  PotentialBuysStore,
  isPotentialBuyId,
  sniffImage,
  MAX_BYTES,
  MAX_LABEL_CHARS,
};
